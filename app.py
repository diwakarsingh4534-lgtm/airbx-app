import streamlit as st
import pickle
import pandas as pd
from openai import OpenAI

with open('airbx_model.pkl', 'rb') as f:
    model = pickle.load(f)


def get_explanation(values, prediction, probability):
    """Ask an NVIDIA Nemotron model (hosted on Nebius) to explain the result in plain English."""
    try:
        client = OpenAI(
            base_url="https://api.tokenfactory.nebius.com/v1/",
            api_key=st.secrets["NEBIUS_API_KEY"],
        )
    except Exception:
        return None  # no key set, so skip the explanation

    label = "persistent" if prediction == 1 else "not persistent"
    prompt = (
        "You explain crypto arbitrage predictions to students in plain English.\n"
        "A machine-learning model predicted whether a price gap between two exchanges will "
        "stay profitable long enough to trade. 'Persistent' means the next opportunity on the "
        "same exchange pair appears within 60 seconds with profit of at least 0.5%.\n\n"
        f"Inputs: {values}\n"
        f"Prediction: {label} ({probability * 100:.1f}% confidence)\n\n"
        "In 3 to 4 short sentences, explain which input values likely support this prediction "
        "and why. Do not invent extra data. End with: This is educational, not financial advice."
    )
    try:
        response = client.chat.completions.create(
            model="nvidia/NVIDIA-Nemotron-3-Nano-30B-A3B",
            messages=[{"role": "user", "content": prompt}],
            temperature=0.3,
            max_tokens=1000,
        )
        text = response.choices[0].message.content or ""
        if "</think>" in text:
            text = text.split("</think>")[-1]
        return text.strip() or "The model returned no text. Please try again."
    except Exception as e:
        return f"Explanation unavailable: {e}"


st.title("AirbX — Arbitrage Persistence Predictor")
st.write("Predict whether a detected cross-exchange arbitrage opportunity will remain profitable long enough to trade.")

st.header("Enter Opportunity Details")

spread_pct = st.number_input("Spread %", min_value=0.0, max_value=100.0, value=2.0)
liquidity_score = st.number_input("Liquidity Score", min_value=0.0, value=100.0)
volatility = st.number_input("Volatility", min_value=0.0, value=0.05)
momentum = st.number_input("Momentum", value=0.0)
arb_amount = st.number_input("Arbitrage Amount", min_value=0.0, value=5.0)
arb_quantity = st.number_input("Arbitrage Quantity", min_value=0.0, value=0.1)

if st.button("Predict Persistence"):
    cols = ['spread_pct', 'liquidity_score', 'volatility', 'momentum', 'arb_amount', 'arb_quantity']
    input_data = pd.DataFrame(
        [[spread_pct, liquidity_score, volatility, momentum, arb_amount, arb_quantity]], columns=cols)

    prediction = model.predict(input_data)[0]
    probability = model.predict_proba(input_data)[0][1]

    if prediction == 1:
        st.success(f"✅ This opportunity is likely PERSISTENT ({probability*100:.1f}% confidence)")
    else:
        st.error(f"❌ This opportunity is likely NOT persistent ({probability*100:.1f}% confidence)")

    with st.spinner("Asking NVIDIA Nemotron (on Nebius) to explain..."):
        explanation = get_explanation(input_data.iloc[0].to_dict(), prediction, probability)
    if explanation:
        st.subheader("Plain-English explanation")
        st.write(explanation)
        st.caption("Generated by an NVIDIA Nemotron model running on Nebius Token Factory. "
                   "It interprets the inputs and is not the Random Forest's internal reasoning.")
